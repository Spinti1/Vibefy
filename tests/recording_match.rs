#[test]
fn conflicting_music_credits_override_a_correct_looking_video_title() {
    let reference = reference("Never Recover", &["Ian", "Azteca"], 116);
    let mut wrong = distributed("Never Recover", "Lil Baby", 116.0);
    wrong.title = Some("Ian Azteca - Never Recover (Official Audio)".into());
    assert!(verified_match(&reference, &wrong).is_none());
    wrong.artists = Some(vec!["Ian".into(), "Azteca".into()]);
    wrong.track = Some("Never Recover 2".into());
    assert!(verified_match(&reference, &wrong).is_none());
}

#[test]
fn distributed_album_audio_wins_over_official_video_and_fan_audio() {
    let reference = reference("Song", &["Artist"], 200);
    let audio = verified_match(&reference, &distributed("Song", "Artist", 200.0)).unwrap();
    let video = verified_match(
        &reference,
        &upload("Artist - Song (Official Video)", "ArtistVEVO", 200.0, true),
    )
    .unwrap();
    assert!(audio.score > video.score);
    let independent = verified_match(
        &reference,
        &upload(
            "Artist - Song (Official Audio)",
            "Fan Channel",
            200.0,
            false,
        ),
    )
    .unwrap();
    assert_eq!(independent.source, SourceKind::MetadataMatch);
    assert!(audio.score > independent.score);
}

#[test]
fn unofficial_modifications_are_rejected_even_at_the_correct_duration() {
    for suffix in [
        "Bass Boosted",
        "8D",
        "TikTok",
        "Mashup",
        "Slowed",
        "Sped Up",
        "Live",
        "Acoustic",
        "Remix",
        "Clean",
    ] {
        let reference = reference("Song", &["Artist"], 200);
        let recording = upload(&format!("Artist - Song ({suffix})"), "Artist", 200.0, true);
        assert!(verified_match(&reference, &recording).is_none(), "{suffix}");
    }
}

#[test]
fn missing_and_mismatched_durations_are_not_proof_of_identity() {
    let reference = reference("Song", &["Artist"], 200);
    let mut recording = distributed("Song", "Artist", 200.0);
    for duration in [None, Some(f64::NAN), Some(0.0), Some(240.0)] {
        recording.duration = duration;
        assert!(verified_match(&reference, &recording).is_none());
    }
}

#[test]
fn longer_video_allowance_requires_a_verified_official_publisher_and_is_bounded() {
    use spotifast::recording_match::duration_compatible;
    assert!(duration_compatible(
        189,
        212,
        "Ian - Flexez (Official Video)",
        true
    ));
    assert!(!duration_compatible(
        189,
        212,
        "Ian - Flexez (Official Video)",
        false
    ));
    assert!(!duration_compatible(
        189,
        212,
        "Ian - Flexez (Official Audio)",
        true
    ));
    assert!(!duration_compatible(
        189,
        250,
        "Ian - Flexez (Official Video)",
        true
    ));
    assert!(!duration_compatible(
        189,
        160,
        "Ian - Flexez (Official Video)",
        true
    ));
}

#[test]
fn incomplete_collaborator_metadata_reduces_confidence_without_blocking_the_song() {
    let reference = reference("Never Recover", &["Ian", "Azteca"], 116);
    let mut recording = distributed("Never Recover", "Ian", 116.0);
    recording.artists = Some(vec!["Ian".into(), "Different Guest".into()]);
    let incomplete = verified_match(&reference, &recording).unwrap();
    recording.artists = Some(vec!["Ian".into(), "Azteca".into()]);
    assert!(verified_match(&reference, &recording).unwrap().score > incomplete.score);
}

#[test]
fn unbadged_label_needs_its_own_rights_and_all_performer_credits() {
    let reference = reference("T.F.C.", &["NANE", "Ian"], 200);
    let mut recording = upload(
        "nopartyboys - T.F.C. (feat. NANE & IAN)",
        "nopartyboys",
        200.0,
        false,
    );
    recording.description = Some("Written by NANE & IAN\n© & ℗ nopartyboys 2019".into());
    assert!(shortlist_score(&reference, &recording).is_some());
    assert_eq!(
        verified_match(&reference, &recording).unwrap().source,
        SourceKind::CreditedPublisher
    );
    recording.channel = Some("Reupload Channel".into());
    assert_eq!(
        verified_match(&reference, &recording).unwrap().source,
        SourceKind::MetadataMatch
    );
    recording.channel = Some("nopartyboys".into());
    recording.description =
        Some("Written by NANE & Different Guest\n© & ℗ nopartyboys 2019".into());
    assert_eq!(
        verified_match(&reference, &recording).unwrap().source,
        SourceKind::MetadataMatch
    );
}

#[test]
fn romanian_diacritics_punctuation_and_featured_artist_credits_are_supported() {
    assert_eq!(
        title_key(
            "NANE - T.F.C. (feat. Ian) (Official Audio)",
            &["NANE".into(), "Ian".into()]
        ),
        "t f c"
    );
    let reference = reference("T.F.C.", &["NANE", "Ian"], 200);
    assert!(
        verified_match(
            &reference,
            &upload(
                "NANE - T.F.C. feat. IAN (Official Video)",
                "NANE",
                200.0,
                true
            )
        )
        .is_some()
    );
    let reference = self::reference("Șoare", &["Artist"], 200);
    assert!(verified_match(&reference, &distributed("Soare", "Artist", 200.0)).is_some());
    let reference = self::reference("Song", &["İİArtist", "Guest"], 200);
    assert!(
        verified_match(
            &reference,
            &upload("İİArtist - Song feat. Guest", "İİArtist", 200.0, true)
        )
        .is_some()
    );
}

#[test]
fn all_artist_boundaries_and_album_are_used_for_queries() {
    let mut reference = reference("Song", &["Artist, With Comma", "Guest"], 200);
    reference.album = "Album Name".into();
    let queries = search_queries(&reference);
    assert!(
        queries
            .iter()
            .any(|query| query.contains("Artist, With Comma Guest"))
    );
    assert!(queries.iter().any(|query| query.contains("Album Name")));
}

#[test]
fn regional_release_labels_do_not_hide_the_same_youtube_recording() {
    let reference = reference(
        "I Don't Care - US Version",
        &["Apocalyptica", "Adam Gontier"],
        221,
    );
    let recording = upload(
        "Apocalyptica - I Don't Care ft. Adam Gontier (Official Video)",
        "Apocalyptica",
        221.0,
        true,
    );
    assert!(verified_match(&reference, &recording).is_some());
    assert!(search_queries(&reference)[0].contains("I Don't Care"));
    assert!(!search_queries(&reference)[0].contains("US Version"));
}

