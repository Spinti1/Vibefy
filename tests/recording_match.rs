#[test]
fn recording_cache_is_bound_to_artist_album_duration_and_validated_provenance() {
    let track = LocalTrack {
        title: "Song".into(),
        artists: vec![ArtistRef {
            name: "Artist".into(),
            ..Default::default()
        }],
        album: "Album".into(),
        duration_ms: 200_000,
        ..Default::default()
    };
    let old: CachedMatch = serde_json::from_str(
        r#"{"youtube_id":"old","title":"Artist - Song","duration_secs":200,"matcher_version":2}"#,
    )
    .unwrap();
    assert!(!old.matches_track(&track));
    let mut cached = CachedMatch {
        matcher_version: spotifast::audio_match::MATCHER_VERSION,
        reference_key: recording_reference_key(&track),
        source_kind: Some(SourceKind::DistributedAudio),
        channel_id: "UC-artist".into(),
        ..old
    };
    assert!(cached.matches_track(&track));
    for variant in [
        LocalTrack {
            artists: vec![ArtistRef {
                name: "Other".into(),
                ..Default::default()
            }],
            ..track.clone()
        },
        LocalTrack {
            album: "Different".into(),
            ..track.clone()
        },
        LocalTrack {
            duration_ms: 201_000,
            ..track.clone()
        },
    ] {
        assert!(!cached.matches_track(&variant));
    }
    cached.source_kind = None;
    assert!(!cached.matches_track(&track));
}
