use spotifast::api::models::ArtistRef;
use spotifast::player::{CachedMatch, LocalTrack, recording_reference_key};
use spotifast::recording_match::{
    Recording, Reference, SourceKind, search_queries, shortlist_score, title_key, verified_match,
};

fn reference(title: &str, artists: &[&str], duration_secs: u32) -> Reference {
    Reference {
        title: title.into(),
        artists: artists.iter().map(|name| (*name).into()).collect(),
        album: title.into(),
        duration_secs,
    }
}

fn upload(title: &str, channel: &str, duration: f64, verified: bool) -> Recording {
    Recording {
        id: "abcdefghijk".into(),
        title: Some(title.into()),
        channel: Some(channel.into()),
        channel_id: Some("UC-example".into()),
        channel_is_verified: Some(verified),
        duration: Some(duration),
        ..Default::default()
    }
}

fn distributed(title: &str, artist: &str, duration: f64) -> Recording {
    Recording {
        track: Some(title.into()),
        artists: Some(vec![artist.into()]),
        description: Some(
            "Provided to YouTube by Distributor\n\nAuto-generated by YouTube.".into(),
        ),
        ..upload(title, &format!("{artist} - Topic"), duration, false)
    }
}

#[test]
fn flexez_official_recording_still_beats_an_acceptable_independent_upload() {
    let reference = reference("Flexez", &["Ian", "Azteca"], 189);
    let fan = upload("Ian-FLEXEZ feat. AZTECA", "Yasmina Official", 199.0, false);
    let official = upload(
        "Ian - Flexez Feat. Azteca (Official Video)",
        "Ocult Records",
        212.0,
        true,
    );
    assert!(shortlist_score(&reference, &fan).is_some());
    let fallback = verified_match(&reference, &fan).unwrap();
    assert_eq!(fallback.source, SourceKind::MetadataMatch);
    assert!(verified_match(&reference, &official).unwrap().score > fallback.score);
    assert_eq!(
        verified_match(&reference, &official).unwrap().source,
        SourceKind::VerifiedPublisher
    );
}

#[test]
fn similar_titles_are_allowed_but_shared_words_and_numbered_sequels_are_distinct() {
    let reference = reference("Never Recover", &["Ian", "Azteca"], 116);
    for title in ["Ian - Never Recover Again", "Ian - Never Recover 2"] {
        assert!(
            verified_match(&reference, &upload(title, "Ian", 116.0, true)).is_none(),
            "{title}"
        );
    }
    let short = self::reference("Love", &["Artist"], 180);
    assert!(
        verified_match(
            &short,
            &upload("Artist - Love Story", "Artist", 180.0, true)
        )
        .is_none()
    );
    assert!(verified_match(&reference, &distributed("Never Recover", "Ian", 116.0)).is_some());
    assert!(
        verified_match(
            &reference,
            &upload("Ian - Recover Never", "Ian", 116.0, true)
        )
        .is_some()
    );
    let typo = verified_match(&reference, &distributed("Never Recove", "Ian", 116.0)).unwrap();
    let exact = verified_match(&reference, &distributed("Never Recover", "Ian", 116.0)).unwrap();
    assert!(exact.score > typo.score);
}

#[test]
fn approximate_title_still_requires_the_right_artist_version_and_duration() {
    let reference = reference("I Am Machine", &["Three Days Grace"], 201);
    assert!(
        verified_match(
            &reference,
            &distributed("I Am Machne", "Three Days Grace", 201.0)
        )
        .is_some()
    );
    for recording in [
        distributed("I Am Machne", "Other Artist", 201.0),
        distributed("I Am Machne", "Three Days Grace", 270.0),
        distributed("I Am Machne (Karaoke)", "Three Days Grace", 201.0),
    ] {
        assert!(verified_match(&reference, &recording).is_none());
    }
}

